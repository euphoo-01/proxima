CREATE OR REPLACE FUNCTION sys.proxima_password_verify(
  username VARCHAR2, password VARCHAR2, old_password VARCHAR2
) RETURN BOOLEAN AUTHID DEFINER IS
BEGIN
  IF password IS NULL OR LENGTH(password) < 16 OR LENGTH(password) > 64
    OR NOT REGEXP_LIKE(password,'[a-z]','c')
    OR NOT REGEXP_LIKE(password,'[A-Z]','c')
    OR NOT REGEXP_LIKE(password,'[0-9]','c')
    OR INSTR(UPPER(password),UPPER(username)) > 0 THEN
    RAISE_APPLICATION_ERROR(-20201,'Database password requires 16-64 characters, upper/lowercase letters and a digit; username is forbidden');
  END IF;
  IF old_password IS NOT NULL AND password=old_password THEN
    RAISE_APPLICATION_ERROR(-20202,'New password must differ from the previous password');
  END IF;
  RETURN TRUE;
END;
