DECLARE
  n PLS_INTEGER;
  PROCEDURE ensure_profile(p_name VARCHAR2,p_limits VARCHAR2) IS
  BEGIN
    SELECT COUNT(*) INTO n FROM dba_profiles WHERE profile=p_name;
    IF n=0 THEN
      EXECUTE IMMEDIATE 'CREATE PROFILE '||p_name||' LIMIT '||p_limits;
    ELSE
      EXECUTE IMMEDIATE 'ALTER PROFILE '||p_name||' LIMIT '||p_limits;
    END IF;
  END;
BEGIN
  ensure_profile('PROXIMA_OWNER_PROFILE',
    'FAILED_LOGIN_ATTEMPTS 3 PASSWORD_LOCK_TIME 1 PASSWORD_LIFE_TIME 180 PASSWORD_GRACE_TIME 7 '||
    'PASSWORD_REUSE_TIME 365 PASSWORD_REUSE_MAX 10 PASSWORD_VERIFY_FUNCTION SYS.PROXIMA_PASSWORD_VERIFY '||
    'SESSIONS_PER_USER 2 IDLE_TIME 15 CONNECT_TIME 120');
  ensure_profile('PROXIMA_RUNTIME_PROFILE',
    'FAILED_LOGIN_ATTEMPTS 5 PASSWORD_LOCK_TIME 1/24 PASSWORD_LIFE_TIME UNLIMITED PASSWORD_GRACE_TIME 7 '||
    'PASSWORD_REUSE_TIME 365 PASSWORD_REUSE_MAX 10 PASSWORD_VERIFY_FUNCTION SYS.PROXIMA_PASSWORD_VERIFY '||
    'SESSIONS_PER_USER 64 IDLE_TIME 30 CONNECT_TIME 480');
  SELECT COUNT(*) INTO n FROM dba_roles WHERE role='PROXIMA_CONNECT_ROLE';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE ROLE proxima_connect_role'; END IF;
  SELECT COUNT(*) INTO n FROM dba_roles WHERE role='PROXIMA_API_ROLE';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE ROLE proxima_api_role'; END IF;
END;
/
GRANT CREATE SESSION TO proxima_connect_role;
